"""
Storage Module for RAG X-Ray
=============================
Handles saving and loading:
1. Document metadata (saved as JSON files in the 'data' directory).
2. Document vector embeddings (saved in ChromaDB under 'data/chroma').
"""
from __future__ import annotations

import json
import os
import threading
import uuid
from pathlib import Path

# Directory where documents and vector database are saved
DATA_DIR = Path(os.getenv('RAG_DATA_DIR', str(Path(__file__).resolve().parents[2] / 'data')))
DATA_DIR.mkdir(parents=True, exist_ok=True)
DATA = DATA_DIR  # Backward-compatible alias for tests

# Thread lock to safely read and write files when multiple requests arrive
FILE_LOCK = threading.RLock()
LOCK = FILE_LOCK  # Backward-compatible alias for tests


def _path(doc_id: str) -> Path:
    """
    Returns the file path for a given document ID (e.g., data/doc_12345.json).
    Validates that the ID is safe and generated by the server.
    """
    if not doc_id.startswith('doc_') or not doc_id[4:].isalnum():
        raise ValueError('Invalid document ID')
    return DATA / f'{doc_id}.json'


def new_doc(filename: str) -> dict:
    """
    Creates a new document entry with an initial 'queued' status
    and saves it to disk.
    """
    document = {
        "id": "doc_" + uuid.uuid4().hex,
        "filename": filename,
        "status": "queued",
        "stages": [],
        "chunks": [],
        "error": None
    }
    put(document)
    return document


def put(doc: dict) -> None:
    """
    Saves document metadata to disk safely.
    Uses atomic write (writes to a .tmp file first, then renames it)
    so data is never corrupted if a crash happens midway.
    """
    file_path = _path(doc['id'])
    with FILE_LOCK:
        temp_path = file_path.with_suffix('.tmp')
        temp_path.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding='utf-8')
        temp_path.replace(file_path)


def get(doc_id: str) -> dict | None:
    """
    Loads and returns a document's metadata from its JSON file.
    Returns None if the document does not exist.
    """
    try:
        file_path = _path(doc_id)
    except ValueError:
        return None

    with FILE_LOCK:
        if not file_path.exists():
            return None
        return json.loads(file_path.read_text(encoding='utf-8'))


def all_docs() -> list[dict]:
    """
    Returns a list of all documents currently saved in the data folder.
    """
    with LOCK:
        documents = []
        for file_path in DATA.glob('doc_*.json'):
            data = json.loads(file_path.read_text(encoding='utf-8'))
            documents.append(data)
    # Sort documents by ID for a consistent display order
    return sorted(documents, key=lambda d: d['id'])


def collection():
    """
    Initializes and returns the ChromaDB vector collection.
    ChromaDB stores all chunk embeddings with cosine distance calculation.
    """
    import chromadb

    chroma_path = str(DATA / 'chroma')
    client = chromadb.PersistentClient(path=chroma_path)
    return client.get_or_create_collection(
        name='rag_xray_chunks',
        metadata={'hnsw:space': 'cosine'}
    )
