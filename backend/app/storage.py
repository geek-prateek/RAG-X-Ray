def _format_time_ago(ts: float) -> str:
    """Formats a Unix epoch timestamp into a friendly human relative time."""
    if not ts:
        return 'Recently'
    now = time.time()
    diff = max(0, int(now - ts))
    if diff < 60:
        return 'Just now'
    elif diff < 3600:
        return f"{diff // 60}m ago"
    elif diff < 86400:
        return f"{diff // 3600}h ago"
    elif diff < 172800:
        return 'Yesterday'
    else:
        return f"{diff // 86400}d ago"


def _workspace_last_activity(sdir: Path) -> float:
    """Returns the latest modification timestamp of any file in this session directory."""
    try:
        latest = sdir.stat().st_mtime
    except Exception:
        latest = 0.0

    try:
        for entry in sdir.rglob('*'):
            try:
                em = entry.stat().st_mtime
                if em > latest:
                    latest = em
            except Exception:
                pass
    except Exception:
        pass
    return latest


def all_workspaces() -> list[dict]:
    """
    Returns all existing local workspaces that actually contain uploaded documents.
    Workspaces are sorted by most recent activity (latest first).
    Workspaces with no documents are pruned and not listed.
    """
    import shutil
    from datetime import datetime
    workspaces = []

    # 1. Check default workspace (only if it contains documents)
    default_docs = all_docs('default')
    if default_docs:
        default_dir = DATA / 'sessions' / 'default'
        default_mtime = _workspace_last_activity(default_dir) if default_dir.exists() else 0.0
        default_history = get_history('default')
        first_doc = default_docs[0]['filename']
        default_name = f"Workspace: {first_doc}"
        if len(default_docs) > 1:
            default_name += f" (+{len(default_docs) - 1})"
        workspaces.append({
            'id': 'default',
            'name': default_name,
            'doc_count': len(default_docs),
            'history_count': len(default_history),
            'updated_at': default_mtime
        })

    # 2. Iterate all session directories in 'data/sessions'
    sessions_folder = DATA / 'sessions'
    if sessions_folder.exists():
        for sdir in sessions_folder.iterdir():
            if not sdir.is_dir() or sdir.name == 'default' or sdir.name.startswith('test_'):
                continue

            sid = sdir.name
            s_docs = all_docs(sid)

            # A workspace should only exist if it actually has uploaded documents!
            if len(s_docs) == 0:
                with FILE_LOCK:
                    shutil.rmtree(sdir, ignore_errors=True)
                continue

            s_history = get_history(sid)
            s_mtime = _workspace_last_activity(sdir)

            # Check for custom name in meta.json
            meta_path = sdir / 'meta.json'
            custom_name = None
            if meta_path.exists():
                try:
                    custom_name = json.loads(meta_path.read_text(encoding='utf-8')).get('name')
                except Exception:
                    pass

            if not custom_name:
                first_name = s_docs[0]['filename']
                custom_name = f"Workspace: {first_name}"
                if len(s_docs) > 1:
                    custom_name += f" (+{len(s_docs) - 1})"

            workspaces.append({
                'id': sid,
                'name': custom_name,
                'doc_count': len(s_docs),
                'history_count': len(s_history),
                'updated_at': s_mtime
            })

    # Sort all workspaces strictly by latest activity descending
    workspaces.sort(key=lambda w: w.get('updated_at', 0.0), reverse=True)

    # Annotate latest flag and readable time_ago
    for i, ws in enumerate(workspaces):
        ws['is_latest'] = (i == 0)
        ws['time_ago'] = _format_time_ago(ws.get('updated_at', 0.0))
        ts = ws.get('updated_at', 0.0)
        ws['last_active'] = datetime.fromtimestamp(ts).strftime('%b %d, %H:%M') if ts > 0 else 'N/A'

    return workspaces


def set_workspace_name(session_id: str, name: str) -> None:
    """Saves a custom friendly name for a workspace."""
    sid = _sanitize_session_id(session_id)
    sdir = _session_dir(sid)
    meta_path = sdir / 'meta.json'
    with FILE_LOCK:
        meta_path.write_text(json.dumps({'name': name}, ensure_ascii=False, indent=2), encoding='utf-8')


def delete_workspace(session_id: str) -> bool:
    """Deletes a local workspace folder and cleans up its ChromaDB vectors."""
    sid = _sanitize_session_id(session_id)
    if sid == 'default':
        return False  # Do not delete default session folder

    sdir = DATA / 'sessions' / sid
    if not sdir.exists():
        return False

    # Delete all documents in session from ChromaDB
    docs = all_docs(sid)
    all_chunk_ids = [c['id'] for d in docs for c in d.get('chunks', [])]
    if all_chunk_ids:
        try:
            collection().delete(ids=all_chunk_ids)
        except Exception:
            pass

    # Delete session directory
    import shutil
    with FILE_LOCK:
        shutil.rmtree(sdir, ignore_errors=True)
    return True


