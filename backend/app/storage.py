def _history_path(session_id: str = 'default') -> Path:
    """Returns the history JSON path for a specific local session."""
    return _session_dir(session_id) / 'history.json'


def get_history(session_id: str = 'default') -> list[dict]:
    """
    Returns the past queries and answers for this local session.
    """
    path = _history_path(session_id)
    with FILE_LOCK:
        if not path.exists():
            return []
        try:
            return json.loads(path.read_text(encoding='utf-8'))
        except Exception:
            return []


def add_history(session_id: str, entry: dict) -> None:
    """
    Appends a new query & answer record to this local session's history.
    Keeps the most recent 50 entries.
    """
    sid = _sanitize_session_id(session_id)
    history = get_history(sid)
    history.insert(0, entry)  # Most recent first
    history = history[:50]

    path = _history_path(sid)
    with FILE_LOCK:
        temp_path = path.with_suffix('.tmp')
        temp_path.write_text(json.dumps(history, ensure_ascii=False, indent=2), encoding='utf-8')
        temp_path.replace(path)


def clear_history(session_id: str = 'default') -> None:
    """
    Clears all query history for this local session.
    """
    sid = _sanitize_session_id(session_id)
    path = _history_path(sid)
    with FILE_LOCK:
        path.unlink(missing_ok=True)


