"""
Storage Module for RAG X-Ray (Local Session Scoped)
===================================================
Handles saving and loading:
1. Document metadata: Scoped per local browser session in 'data/sessions/<session_id>/doc_*.json'.
2. Local Query History: Saved in 'data/sessions/<session_id>/history.json'.
3. Vector embeddings: Saved in ChromaDB with 'session_id' metadata for full isolation.

This ensures:
- No global mixing: Every browser gets its own private local workspace.
- User questions and documents are strictly local to that session.
"""
from __future__ import annotations

import json
import os
import threading
import time
import uuid
from pathlib import Path

# Base data directory
DATA_DIR = Path(os.getenv('RAG_DATA_DIR', str(Path(__file__).resolve().parents[2] / 'data')))
DATA_DIR.mkdir(parents=True, exist_ok=True)
DATA = DATA_DIR  # Backward-compatible alias for unit tests

# Thread lock to safely read and write files when multiple requests arrive
FILE_LOCK = threading.RLock()
LOCK = FILE_LOCK  # Backward-compatible alias for unit tests


def _sanitize_session_id(session_id: str | None) -> str:
    """Sanitizes session ID to prevent directory traversal; defaults to 'default'."""
    if not session_id:
        return 'default'
    # Keep only alphanumeric, hyphens and underscores
    clean = ''.join(c for c in session_id if c.isalnum() or c in ('-', '_'))
    return clean if clean else 'default'


def _session_dir(session_id: str = 'default') -> Path:
    """Returns the directory for a specific local session."""
    sid = _sanitize_session_id(session_id)
    folder = DATA / 'sessions' / sid
    folder.mkdir(parents=True, exist_ok=True)
    return folder


def _path(doc_id: str, session_id: str = 'default') -> Path:
    """
    Returns the file path for a given document ID within a session.
    Validates that the ID is safe and generated by the server.
    """
    if not doc_id.startswith('doc_') or not doc_id[4:].isalnum():
        raise ValueError('Invalid document ID')
    return _session_dir(session_id) / f'{doc_id}.json'


def new_doc(filename: str, session_id: str = 'default') -> dict:
    """
    Creates a new document entry with an initial 'queued' status
    and saves it inside the session's local folder.
    """
    sid = _sanitize_session_id(session_id)
    document = {
        "id": "doc_" + uuid.uuid4().hex,
        "session_id": sid,
        "filename": filename,
        "status": "queued",
        "stages": [],
        "chunks": [],
        "error": None
    }
    put(document, session_id=sid)
    return document


def put(doc: dict, session_id: str | None = None) -> None:
    """
    Saves document metadata to disk safely.
    Uses atomic write (writes to a .tmp file first, then renames it).
    """
    sid = _sanitize_session_id(session_id or doc.get('session_id', 'default'))
    doc['session_id'] = sid
    file_path = _path(doc['id'], session_id=sid)

    with FILE_LOCK:
        temp_path = file_path.with_suffix('.tmp')
        temp_path.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding='utf-8')
        temp_path.replace(file_path)


def save_raw_file(doc_id: str, filename: str, content: bytes, session_id: str = 'default') -> Path:
    """
    Saves the uploaded raw document file (PDF, TXT, MD) into the session's files folder.
    This enables full in-browser reading and direct tab viewing.
    """
    sid = _sanitize_session_id(session_id)
    files_dir = _session_dir(sid) / 'files'
    files_dir.mkdir(parents=True, exist_ok=True)

    clean_name = Path(filename).name
    file_path = files_dir / f"{doc_id}_{clean_name}"
    with FILE_LOCK:
        file_path.write_bytes(content)
    return file_path


def get_raw_file(doc_id: str, session_id: str = 'default') -> Path | None:
    """
    Locates the raw document file on disk for a given doc_id.
    """
    sid = _sanitize_session_id(session_id)
    files_dir = _session_dir(sid) / 'files'
    if files_dir.exists():
        for f in files_dir.glob(f"{doc_id}_*"):
            if f.is_file():
                return f

    # Check default and legacy locations
    for legacy_f in DATA.glob(f"sessions/*/files/{doc_id}_*"):
        if legacy_f.is_file():
            return legacy_f
    return None


def delete_raw_file(doc_id: str, session_id: str = 'default') -> None:
    """
    Removes raw document files for a doc_id when deleted.
    """
    sid = _sanitize_session_id(session_id)
    files_dir = _session_dir(sid) / 'files'
    if files_dir.exists():
        for f in files_dir.glob(f"{doc_id}_*"):
            try:
                f.unlink(missing_ok=True)
            except Exception:
                pass


def get(doc_id: str, session_id: str | None = None) -> dict | None:
    """
    Loads and returns a document's metadata from its JSON file.
    If session_id is provided, looks inside that session.
    Otherwise searches default session and all sessions for backward compatibility.
    """
    try:
        if session_id:
            sid = _sanitize_session_id(session_id)
            target = _path(doc_id, sid)
            with FILE_LOCK:
                if target.exists():
                    return json.loads(target.read_text(encoding='utf-8'))
                # Also check root DATA for backward compatibility
                legacy = DATA / f'{doc_id}.json'
                if legacy.exists():
                    return json.loads(legacy.read_text(encoding='utf-8'))
                return None

        # No session specified: check default session, then root DATA, then any session
        default_target = _path(doc_id, 'default')
        with FILE_LOCK:
            if default_target.exists():
                return json.loads(default_target.read_text(encoding='utf-8'))

            legacy = DATA / f'{doc_id}.json'
            if legacy.exists():
                return json.loads(legacy.read_text(encoding='utf-8'))

            for match in DATA.glob('sessions/*/doc_*.json'):
                if match.name == f'{doc_id}.json':
                    return json.loads(match.read_text(encoding='utf-8'))
            return None
    except ValueError:
        return None


def all_docs(session_id: str = 'default') -> list[dict]:
    """
    Returns a list of all documents belonging to this local session.
    """
    sid = _sanitize_session_id(session_id)
    session_folder = _session_dir(sid)

    with FILE_LOCK:
        documents = []
        if session_folder.exists():
            for file_path in session_folder.glob('doc_*.json'):
                try:
                    data = json.loads(file_path.read_text(encoding='utf-8'))
                    documents.append(data)
                except Exception:
                    pass

        # If in 'default' session, also load any legacy root docs
        if sid == 'default':
            for file_path in DATA.glob('doc_*.json'):
                try:
                    data = json.loads(file_path.read_text(encoding='utf-8'))
                    if not any(d['id'] == data['id'] for d in documents):
                        documents.append(data)
                except Exception:
                    pass

    return sorted(documents, key=lambda d: d['id'])


